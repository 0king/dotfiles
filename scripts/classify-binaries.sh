#!/usr/bin/env bash
# ==============================================================================
# classify-binaries.sh: Dynamic Classifier for ~/.local/bin Binaries & Symlinks
# Auto-detects compiled ELF binaries (\x7fELF) and unmanaged external symlinks,
# generating package-local bin/.local/bin/.gitignore rules dynamically.
# ==============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DOTFILES_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
BIN_DIR="$DOTFILES_DIR/bin/.local/bin"
GITIGNORE="$BIN_DIR/.gitignore"

[ -d "$BIN_DIR" ] || exit 0

HEADER="# ==============================================================================
# Auto-generated by scripts/classify-binaries.sh
# Dynamic classification: compiled ELF binaries and unmanaged external tool symlinks
# DO NOT EDIT MANUALLY - run 'scripts/classify-binaries.sh' or 'dotfiles status'
# =============================================================================="

IGNORES=()

for item in "$BIN_DIR"/* "$BIN_DIR"/.*; do
    [ -e "$item" ] || [ -L "$item" ] || continue
    name="$(basename "$item")"

    # Skip . and .. and .gitignore itself
    if [ "$name" = "." ] || [ "$name" = ".." ] || [ "$name" = ".gitignore" ]; then
        continue
    fi

    # Skip directories (e.g. code, docs, out)
    if [ -d "$item" ] && [ ! -L "$item" ]; then
        continue
    fi

    # Check if symlink
    if [ -L "$item" ]; then
        target="$(readlink "$item")"
        # If symlink points outside dotfiles repo, treat as unmanaged external tool
        case "$target" in
            *"dotfiles"*) ;; # points within dotfiles
            *)
                IGNORES+=("$name")
                ;;
        esac
        continue
    fi

    # Check if regular file and compiled ELF binary
    if [ -f "$item" ]; then
        magic="$(head -c 4 "$item" 2>/dev/null || true)"
        if [ "$magic" = $'\x7fELF' ]; then
            IGNORES+=("$name")
        fi
    fi
done

# Sort and deduplicate ignores
sorted_ignores="$(printf "%s\n" "${IGNORES[@]}" 2>/dev/null | sort -u || true)"

{
    echo "$HEADER"
    if [ -n "$sorted_ignores" ]; then
        echo "$sorted_ignores"
    fi
} > "$GITIGNORE"
